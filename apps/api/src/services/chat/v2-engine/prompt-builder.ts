/**
 * Generate Shot 2 (remove-from-cart) using a real product name from the
 * store catalog. If no catalog items are available, falls back to a
 * generic placeholder ("produk ini") — NEVER food-specific.
 */
export function buildDynamicRemoveShot(catalogItems?: CatalogItemForPrompt[]): string {
  const productName = (catalogItems && catalogItems.length > 0)
    ? catalogItems[0].name
    : 'produk ini';

  const escapedProduct = productName.replace(/"/g, '');

  return `{
  "schema_version": "v1",
  "intent": "modify_cart",
  "confidence": 0.95,
  "entities": [
    {"type": "product", "value": "${escapedProduct}", "confidence": 0.95}
  ],
  "proposed_actions": [
    {"action_type": "REMOVE_FROM_CART", "payload": {"product": "${escapedProduct}"}, "confidence": 0.95, "requires_validation": true}
  ],
  "reply_text": "Oke, ${escapedProduct} sudah dihapus dari keranjang. Ada yang ingin ditambahkan lagi?",
  "needs_clarification": false,
  "summary_update": "Customer membatalkan ${escapedProduct} dari keranjang."
}`;
}

