/**
 * Assemble the full prompt sent to the LLM: system prompt (with optional
 * business context + dynamic few-shots) + context string.
 *
 * @param context    The pre-assembled context string from buildLLMContext()
 *                   (UNIT2). Already contains STATE + HISTORY + PESAN SEKARANG.
 * @param opts       Optional contextual injection:
 *                   - businessCategory: store's business category (e.g. "Spare Parts")
 *                   - catalogItems: pre-filtered catalog for dynamic Shot 2 + catalog layer
 */
export function buildV2Prompt(context: string, opts?: BuildV2PromptOptions): string {
  const { businessCategory, catalogItems } = opts ?? {};

  // ── Business context sentence (reuse pola V1 prompt-builder.service.ts) ──
  const businessSentence = businessCategory
    ? `You are an AI assistant for a ${businessCategory} store.`
    : '';

  // ── Dynamic Shot 2 (remove-from-cart) using real catalog product ──
  const dynamicShot2 = buildDynamicRemoveShot(catalogItems);

  // ── Assemble system prompt with business context + dynamic shot ──
  const systemPrompt = `${businessSentence ? businessSentence + '\n\n' : ''}${V2_ENGINE_SYSTEM_PROMPT_BASE}

=== CONTOH (FEW-SHOT) ===

Example 1 — Add to cart with variant
Customer: "Saya mau beli sepatu warna merah size L"
${V2_ENGINE_FEW_SHOTS[0].expected_json}

Example 2 — Remove item from cart (modify_cart) [DYNAMIC — product from real catalog]
Customer: "Eh, ${catalogItems && catalogItems.length > 0 ? catalogItems[0].name : 'produk ini'} ga jadi deh"
${dynamicShot2}

Example 3 — Ask total
Customer: "Totalnya berapa?"
${V2_ENGINE_FEW_SHOTS[2].expected_json}

Example 4 — False-cancel prevention: "ga jadi" for one item ≠ cancel entire order
Customer: "Eh, ban dalam ga jadi deh, tinggal ban depan aja"
${V2_ENGINE_FEW_SHOTS[3].expected_json}

Example 5 — Variant confirmation: if variant already mentioned in prior turn, short "ya" confirmation → ADD_TO_CART (Rule 13)
Customer: "Ban dalam motor ukuran 100/90-17, ya tambahkan ke keranjang."
${V2_ENGINE_FEW_SHOTS[4].expected_json}
`;

  return `${systemPrompt}\n\n=== KONTeks ===\n${context}`;
}
