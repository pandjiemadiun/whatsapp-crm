/** Single few-shot example: user message + expected JSON output. */
export interface V2FewShot {
  user_message: string;
  expected_json: string;
}

/** Options for buildV2Prompt — contextual injection of store identity + catalog. */
export interface BuildV2PromptOptions {
  /** Store business category (e.g. "Spare Parts") — injected as 1 contextual sentence. */
  businessCategory?: string | null;
  /** Pre-filtered catalog items — used for dynamic few-shot Shot 2 + catalog layer. */
  catalogItems?: CatalogItemForPrompt[];
}

/** Minimal catalog item shape for prompt injection (avoids coupling to setops.js). */
export interface CatalogItemForPrompt {
  id: string;
  name: string;
  price: number;
  category: string | null;
}

